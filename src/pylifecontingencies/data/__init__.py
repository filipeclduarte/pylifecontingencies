"""Bundled life tables and loaders."""

from __future__ import annotations

from pathlib import Path
from typing import Optional

import pandas as pd

from ..lifetable import LifeTable
from ..fractional import FractionalAge

_DATA_DIR = Path(__file__).parent

_BUILTIN_TABLES = {
    # SOA Illustrative Life Table (Bowers et al., ages 0–99)
    "soa_ilt": "soa_ilt.csv",
    # BR-EMS 2021 (ages 0–117/116)
    "br_emssb_2021_m": "br_emssb_2021_m.csv",
    "br_emssb_2021_f": "br_emssb_2021_f.csv",
    "br_emsmt_2021_m": "br_emsmt_2021_m.csv",
    "br_emsmt_2021_f": "br_emsmt_2021_f.csv",
    # BR-EMS 2015 (ages 0–118)
    "br_emssb_2015_m": "br_emssb_2015_m.csv",
    "br_emssb_2015_f": "br_emssb_2015_f.csv",
    "br_emsmt_2015_m": "br_emsmt_2015_m.csv",
    "br_emsmt_2015_f": "br_emsmt_2015_f.csv",
    # BR-EMS 2010 (ages 0–116/113)
    "br_emssb_2010_m": "br_emssb_2010_m.csv",
    "br_emssb_2010_f": "br_emssb_2010_f.csv",
    "br_emsmt_2010_m": "br_emsmt_2010_m.csv",
    "br_emsmt_2010_f": "br_emsmt_2010_f.csv",
}


def load_table(
    name: str,
    fractional: FractionalAge = FractionalAge.UDD,
    column: Optional[str] = None,
) -> LifeTable:
    """
    Load a bundled life table by name.

    Parameters
    ----------
    name : str
        Table identifier. Built-in tables:

        - ``"soa_ilt"`` — SOA Illustrative Life Table (Bowers et al., ages 0–99)
        - ``"br_emssb_2021_m"`` / ``"br_emssb_2021_f"`` — BR-EMS Sobrevivência 2021
        - ``"br_emsmt_2021_m"`` / ``"br_emsmt_2021_f"`` — BR-EMS Mortalidade 2021
        - ``"br_emssb_2015_m"`` / ``"br_emssb_2015_f"`` — BR-EMS Sobrevivência 2015
        - ``"br_emsmt_2015_m"`` / ``"br_emsmt_2015_f"`` — BR-EMS Mortalidade 2015
        - ``"br_emssb_2010_m"`` / ``"br_emssb_2010_f"`` — BR-EMS Sobrevivência 2010
        - ``"br_emsmt_2010_m"`` / ``"br_emsmt_2010_f"`` — BR-EMS Mortalidade 2010

        R-sourced tables (generated by ``scripts/convert_rda_to_parquet.py``):

        - ``"soa08"`` — 2001 CSO (SOA)
        - ``"AM92Lt"`` / ``"AF92Lt"`` — UK AM92 / AF92
        - ``"demoUsa"`` / ``"demoUk"`` / ``"demoIta"`` / ``"demoFrance"``
        - ``"demoGermany"`` / ``"demoJapan"`` / ``"demoChina"`` / ``"demoCanada"``

    fractional : FractionalAge
        Fractional-age assumption to attach to the returned LifeTable.

    column : str, optional
        For multi-column parquet tables (``demo*``), the data column to use as
        ``lx`` or ``qx``.  If omitted and only one data column exists the column
        is chosen automatically.  If omitted and multiple columns exist, a
        ``ValueError`` is raised listing the available column names.

        Example::

            load_table("demoUsa", column="USSS2007M")
            load_table("demoGermany", column="qxMale")

    Returns
    -------
    LifeTable
    """
    # ------------------------------------------------------------------ #
    # CSV built-in tables                                                 #
    # ------------------------------------------------------------------ #
    if name in _BUILTIN_TABLES:
        path = _DATA_DIR / _BUILTIN_TABLES[name]
        df = pd.read_csv(path)
        return LifeTable.from_dataframe(
            df, age_col="age", qx_col="qx", name=name, fractional=fractional
        )

    # ------------------------------------------------------------------ #
    # Parquet tables (R-sourced)                                          #
    # ------------------------------------------------------------------ #
    parquet_path = _DATA_DIR / f"{name}.parquet"
    if parquet_path.exists():
        df = pd.read_parquet(parquet_path)
        data_cols = [c for c in df.columns if c != "age"]

        # Single-column tables: lx or qx directly
        if len(data_cols) == 1:
            col = data_cols[0]
        elif column is not None:
            if column not in data_cols:
                raise ValueError(
                    f"Column '{column}' not found in '{name}'. "
                    f"Available: {data_cols}"
                )
            col = column
        else:
            raise ValueError(
                f"'{name}' contains multiple data columns — specify one with "
                f"column=<name>.\nAvailable: {data_cols}"
            )

        col_name = f"{name}/{col}"
        # Detect lx vs qx by magnitude: lx radix is typically ≥ 1 000
        sample = df[col].dropna()
        if sample.max() >= 2.0:
            return LifeTable.from_dataframe(
                df[["age", col]].rename(columns={col: "lx"}),
                age_col="age", lx_col="lx", name=col_name, fractional=fractional,
            )
        else:
            return LifeTable.from_dataframe(
                df[["age", col]].rename(columns={col: "qx"}),
                age_col="age", qx_col="qx", name=col_name, fractional=fractional,
            )

    available = list(_BUILTIN_TABLES.keys()) + [
        p.stem for p in _DATA_DIR.glob("*.parquet")
    ]
    raise ValueError(
        f"Unknown table '{name}'. Available: {available}. "
        "Run scripts/convert_rda_to_parquet.py to import tables from R."
    )


def list_columns(name: str) -> list[str]:
    """
    Return the data columns available in a multi-column parquet table.

    Useful for ``demo*`` tables which bundle several life tables in one file.

    Example
    -------
    >>> list_columns("demoUsa")
    ['USSS2007M', 'USSS2007F', 'USSS2000M', 'USSS2000F', 'USSS1990M', 'USSS1990F']
    """
    parquet_path = _DATA_DIR / f"{name}.parquet"
    if not parquet_path.exists():
        raise ValueError(f"No parquet file found for '{name}'")
    df = pd.read_parquet(parquet_path, columns=None)
    return [c for c in df.columns if c != "age"]


def list_tables() -> list[str]:
    """Return names of all available bundled tables."""
    parquet_names = [p.stem for p in _DATA_DIR.glob("*.parquet")]
    return sorted(list(_BUILTIN_TABLES.keys()) + parquet_names)
